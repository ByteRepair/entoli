// Generates lib/data/privacy_policy_data.dart from PRIVACY.md at the repo
// root. Run by tool/prepare.sh. The policy is embedded in code rather than
// shipped as a Flutter asset so it renders in-app without a network link.
import "dart:io";

void main() {
  final source = File("PRIVACY.md");
  if (!source.existsSync()) {
    stderr.writeln("PRIVACY.md not found at the repo root.");
    exit(1);
  }
  final content = source.readAsStringSync();

  final buf = StringBuffer();
  buf.writeln("// GENERATED by tool/gen_privacy_policy.dart — do not edit.");
  buf.writeln("// The privacy policy, embedded so About can render it offline.");
  buf.writeln();
  buf.writeln("const String bundledPrivacyPolicy = ${_stringLiteral(content)};");
  buf.writeln();

  File("lib/data/privacy_policy_data.dart").writeAsStringSync(buf.toString());
  stdout.writeln("Wrote lib/data/privacy_policy_data.dart "
      "(${content.length} characters).");
}

/// A Dart string literal, escaped and wrapped in double quotes. Same escaping
/// as gen_bundled_skills.dart: `$` is escaped so markdown links in the policy
/// are not read as Dart interpolations.
String _stringLiteral(String s) {
  final escaped = s
      .replaceAll("\\", "\\\\")
      .replaceAll('"', '\\"')
      .replaceAll("\$", r"\$")
      .replaceAll("\n", '\\n"\n    "');
  return '"$escaped"';
}