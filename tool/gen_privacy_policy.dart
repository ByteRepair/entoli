// Generates lib/data/privacy_policy_data.dart from PRIVACY.md at the repo
// root. Run by tool/prepare.sh. The policy is embedded in code rather than
// shipped as a Flutter asset so it renders in-app without a network link.
import "dart:io";

import "gen_common.dart";

void main() {
  final source = File("PRIVACY.md");
  if (!source.existsSync()) {
    stderr.writeln("PRIVACY.md not found at the repo root.");
    exit(1);
  }
  final content = source.readAsStringSync();

  final buf = StringBuffer();
  buf.writeln("// GENERATED by tool/gen_privacy_policy.dart — do not edit.");
  buf.writeln("// The privacy policy, embedded so About can render it offline.");
  buf.writeln();
  buf.writeln("const String bundledPrivacyPolicy = ${stringLiteral(content)};");
  buf.writeln();

  writeGenerated("lib/data/privacy_policy_data.dart", buf);
}