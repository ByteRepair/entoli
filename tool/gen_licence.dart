// Generates lib/data/licence_data.dart from LICENSE at the repo root. Run by
// tool/prepare.sh. The welcome tour shows it, so it is embedded rather than
// fetched.
import "dart:io";

import "gen_common.dart";

void main() {
  final source = File("LICENSE");
  if (!source.existsSync()) {
    stderr.writeln("LICENSE not found at the repo root.");
    exit(1);
  }
  // Reflowed into paragraphs: the file is hard-wrapped at 80 columns, which a
  // phone's width wraps a second time mid-line.
  final paragraphs = [
    for (final block in normalizeCr(source.readAsStringSync()).split(RegExp(r"\n\s*\n")))
      if (block.trim().isNotEmpty)
        block.split("\n").map((l) => l.trim()).join(" "),
  ];

  final buf = StringBuffer();
  buf.writeln("// GENERATED by tool/gen_licence.dart — do not edit.");
  buf.writeln("// Entoli's licence, one string per paragraph, for the welcome tour.");
  buf.writeln();
  buf.writeln("const bundledLicence = <String>[");
  for (final p in paragraphs) {
    buf.writeln("  ${stringLiteral(p)},");
  }
  buf.writeln("];");

  writeGenerated("lib/data/licence_data.dart", buf);
}
