"""Render the Windows runner icon from the PWA icon.

The AppImage takes its icon straight from `web/icons/` and macOS compiles its
own `.icon` package; this is the Windows half of the same story, reading
`web/icons/Icon-512.png` so one rendered image is the default icon everywhere.
Stdlib only — no PIL, no Homebrew — so it runs wherever the icon needs
refreshing, and the committed .ico can be regenerated byte-for-byte.
"""

import struct
import sys
import zlib
from pathlib import Path

# Downscale from the source, small to large; 0 in an ICONDIRENTRY means 256.
SIZES = [16, 24, 32, 48, 64, 128, 256]


def decode_png(data: bytes) -> tuple[int, int, list[list[bytes]]]:
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    width = height = depth = ctype = None
    idat = b""
    pos = 8
    while pos < len(data):
        length = struct.unpack(">I", data[pos : pos + 4])[0]
        kind = data[pos + 4 : pos + 8]
        chunk = data[pos + 8 : pos + 8 + length]
        if kind == b"IHDR":
            width, height, depth, ctype = struct.unpack(">IIBB", chunk[:10])
        elif kind == b"IDAT":
            idat += chunk
        elif kind == b"IEND":
            break
        pos += 12 + length
    assert (depth, ctype) == (8, 6), "expected 8-bit RGBA, non-interlaced"
    # Rows arrive filtered; bpp is 4 because every pixel is RGBA.
    raw = zlib.decompress(idat)
    stride = width * 4
    rows = []
    previous = bytearray(stride)
    for start in range(0, len(raw), stride + 1):
        # Unfilter in place, restoring first-byte-predicted values per the
        # PNG spec, then keep an unfiltered copy for Paeth and Up below.
        def paeth(a: int, b: int, c: int) -> int:
            p = a + b - c
            pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
            if pa <= pb and pa <= pc:
                return a
            return b if pb <= pc else c

        row = bytearray(raw[start + 1 : start + 1 + stride])
        kind = raw[start]
        for i in range(stride):
            left = row[i - 4] if i >= 4 else 0
            up = previous[i]
            up_left = previous[i - 4] if i >= 4 else 0
            if kind == 1:
                row[i] = (row[i] + left) & 0xFF
            elif kind == 2:
                row[i] = (row[i] + up) & 0xFF
            elif kind == 3:
                row[i] = (row[i] + (left + up) // 2) & 0xFF
            elif kind == 4:
                row[i] = (row[i] + paeth(left, up, up_left)) & 0xFF
        rows.append(bytes(row))
        previous = row
    return width, height, rows


def resize(
    width: int, height: int, rows: list[bytes], size: int
) -> list[bytes]:
    """Box-average downscale; the source is never smaller than the target.

    The average runs in premultiplied space: a transparent pixel's raw RGB
    is otherwise full weight on it, and where the icon fades out the edges
    darken against whatever they sit on. The ratio between the summed
    premultiplied value and the summed alpha is the same as between the
    averages, so the unpremultiply reads both sums directly.
    """
    scale = width / size
    sy = height / size
    out = []
    for y in range(size):
        top, bottom = int(y * sy), max(int(y * sy) + 1, int((y + 1) * sy))
        line = bytearray()
        for x in range(size):
            left = int(x * scale)
            right = max(left + 1, int((x + 1) * scale))
            px = [0, 0, 0, 0]
            n = (bottom - top) * (right - left)
            for r in rows[top:bottom]:
                for i in range(left * 4, right * 4, 4):
                    a = r[i + 3]
                    px[0] += r[i] * a // 255
                    px[1] += r[i + 1] * a // 255
                    px[2] += r[i + 2] * a // 255
                    px[3] += a
            alpha = px[3] // n
            if alpha == 0:
                line.extend((0, 0, 0, alpha))
            else:
                line.extend(
                    min(255, (px[j] * 255 + px[3] // 2) // px[3])
                    for j in range(3)
                )
                line.append(alpha)
        out.append(bytes(line))
    return out


def bmp_entry(rows: list[bytes], size: int) -> bytes:
    """A 32-bit BMP layer: BGRA rows bottom-up, then the (empty) AND mask."""
    header = struct.pack(
        "<IiiHHIIiiII", 40, size, size * 2, 1, 32, 0, 0, 0, 0, 0, 0
    )
    xor = b"".join(
        b"".join(
            struct.pack("4B", r[x * 4 + 2], r[x * 4 + 1], r[x * 4], r[x * 4 + 3])
            for x in range(size)
        )
        for r in reversed(rows)
    )
    # All zero: alpha carries the shape, and Windows then ignores this mask.
    mask = b"\0" * (size * ((size + 31) // 32 * 4))
    return header + xor + mask


def write_ico(target: Path, frames: list[bytes], sizes: list[int]) -> None:
    entries = b""
    offset = 6 + 16 * len(frames)
    images = b""
    for frame, size in zip(frames, sizes):
        entries += struct.pack(
            "<BBBBHHII", size % 256, size % 256, 0, 0, 1, 32, len(frame), offset
        )
        images += frame
        offset += len(frame)
    target.write_bytes(struct.pack("<HHH", 0, 1, len(frames)) + entries + images)


def main() -> None:
    root = Path(__file__).resolve().parent.parent.parent
    source = root / "web/icons/Icon-512.png"
    target = root / "windows/runner/resources/app_icon.ico"
    width, height, rows = decode_png(source.read_bytes())
    assert width == height, "the source icon is square"
    frames = [bmp_entry(resize(width, height, rows, s), s) for s in SIZES]
    write_ico(target, frames, SIZES)
    print(f"wrote {target.relative_to(root)} from {source.name}")


if __name__ == "__main__":
    sys.exit(main())