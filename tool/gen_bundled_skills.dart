// Generates lib/data/prompts/bundled_skill_data.dart from the source tree
// under assets/prompts/ and from the fetched tree under
// build/skills-upstream/. Run by tool/prepare.sh before build_runner.
//
// The bundled skills and agents are embedded in code rather than shipped as
// Flutter assets: the app is the source of truth for the presets, and the
// disk copy under skills-bundled/ is a self-healed cache for bash access.
// Agents are code-only — never written to disk — since nothing reads them
// by path.
//
// The fetched skills are tool/fetch-skills.sh's latest release of
// ByteRepair/skills, copied wholesale: what a release ships is the fork's
// decision, made by its RELEASE_EXCLUDED and release script, and not ours to
// second-guess here. They are embedded unscoped — tagged with the default
// project, inherited by every other — and land only where the source tree
// has no skill of the same name, which keeps the locally adapted files the
// source of truth for the skills we carry ourselves. Every skill's SKILL.md
// is still validated against the Agent Skills spec before it is embedded:
// the loader skips a non-conformant skill with a log line, so a preset that
// did not conform would silently ship broken.
//
// Each entry is tagged with the project it belongs to. `default` is the base
// set every project inherits; another project's entries override a
// same-named default one for that project alone. See "Skills and agents" in
// lib/domain/CLAUDE.md.
import "dart:convert";
import "dart:io";

import "package:agent_chat/data/prompts/skill_validate.dart";
import "package:agent_chat/domain/bundled_prompt_file.dart";
import "package:agent_chat/domain/frontmatter.dart";

import "gen_common.dart";

/// Where the fetched tree lands; the same path tool/fetch-skills.sh extracts
/// to. Under `build/`, so it is gitignored and never reviewed as a diff.
const skillsUpstreamDir = "build/skills-upstream/skills";

void main() {
  final skills = <BundledPromptFile>[];
  final agents = <BundledPromptFile>[];
  for (final projectDir in promptProjects()) {
    final project = basename(projectDir.path);
    final skillsRoot = Directory("${projectDir.path}/skills");
    if (skillsRoot.existsSync()) {
      for (final skillDir in skillsRoot.listSync().whereType<Directory>()) {
        for (final e in _collectSkill(skillDir, project)) {
          skills.add(e);
        }
      }
    }
    final agentsRoot = Directory("${projectDir.path}/agents");
    if (agentsRoot.existsSync()) {
      for (final e in _collectAgents(agentsRoot, project)) {
        agents.add(e);
      }
    }
  }

  final local = skills.map((e) => e.name).toSet();
  final upstream = Directory(skillsUpstreamDir);
  if (upstream.existsSync()) {
    for (final skillDir in upstream.listSync().whereType<Directory>()) {
      final name = basename(skillDir.path);
      if (local.contains(name)) continue;
      final entries = _collectSkill(skillDir, "default");
      skills.addAll(entries);
      // A skill that cannot say what redistribution it allows is not one to
      // ship silently. The release is supposed to have filtered that out.
      if (entries.every((e) => e.relativePath != "LICENSE.txt")) {
        stderr.writeln("gen_bundled_skills: fetched skill $name carries no "
            "LICENSE.txt — the release should have excluded it.");
      }
    }
  } else {
    stderr.writeln("gen_bundled_skills: no fetched skills at "
        "$skillsUpstreamDir — run tool/fetch-skills.sh. Bundling the local "
        "skills alone.");
  }

  sortByProject(skills);
  sortByProject(agents);

  final buf = StringBuffer();
  buf.writeln("// GENERATED by tool/gen_bundled_skills.dart — do not edit.");
  buf.writeln("// The bundled skills and agents, embedded so the app is the");
  buf.writeln("// source of truth for presets. Regenerate with prepare.sh.");
  buf.writeln();
  buf.writeln('import "../../domain/bundled_prompt_file.dart" '
      'show BundledPromptFile;');
  buf.writeln();

  emitPromptFileList(buf, "bundledSkillFiles", skills);
  emitPromptFileList(buf, "bundledAgentFiles", agents);

  writeGenerated("lib/data/prompts/bundled_skill_data.dart", buf);
  stdout.writeln("(${skills.length} skill files, ${agents.length} agent files).");
}

/// Collects every file under one skill folder: [skillDir] is the folder the
/// skill is addressed by, [relativePath] the path within it. The SKILL.md is
/// validated first — a preset that does not conform would be skipped by the
/// loader, so generation refuses it here where the failure is a build
/// failure rather than a silent one. A file that is not text at all — a
/// font, an archive — is embedded base64 with [BundledPromptFile.binary],
/// where `readAsStringSync` could only have thrown or mangled it.
List<BundledPromptFile> _collectSkill(
    Directory skillDir, String project) {
  final skillName = basename(skillDir.path);
  final entries = <BundledPromptFile>[];
  final skillMd = File("${skillDir.path}/SKILL.md");
  if (skillMd.existsSync()) {
    final parsed = Frontmatter.parse(skillMd.readAsStringSync());
    final problems = skillFrontmatterProblems(parsed, skillName);
    if (problems.isNotEmpty) {
      stderr.writeln(
          "bundled skill $project/$skillName does not conform to the "
          "Agent Skills spec:");
      for (final problem in problems) {
        stderr.writeln("  - $problem");
      }
      exitCode = 1;
    }
  }
  for (final file in allFiles(skillDir)) {
    final relative = file.substring(skillDir.path.length + 1);
    final binary = _isBinary(File(file));
    final content = binary
        ? base64Encode(File(file).readAsBytesSync())
        : File(file).readAsStringSync();
    final sha = binary
        ? sha256OfBytes(File(file).readAsBytesSync())
        : sha256Of(content);
    entries.add(BundledPromptFile(
        project, skillName, relative, sha, content,
        binary: binary));
  }
  return entries;
}

/// Whether a file is binary rather than text: a NUL byte anywhere, or a
/// sequence the UTF-8 decoder refuses. Everything the fetched tree carries
/// as text — SKILL.md, scripts, the licences — decodes cleanly, so the sniff
/// is for the fonts and archives, where those are the only two tells there
/// are.
bool _isBinary(File file) {
  final bytes = file.readAsBytesSync();
  if (bytes.contains(0)) return true;
  try {
    utf8.decode(bytes, allowMalformed: false);
    return false;
  } on FormatException {
    return true;
  }
}

/// Walks the `agents/` directory of a project: one `.md` file per agent, named
/// by the filename without extension. [relativePath] is empty.
List<BundledPromptFile> _collectAgents(Directory agentsRoot, String project) {
  final entries = <BundledPromptFile>[];
  for (final entity in agentsRoot.listSync()) {
    if (entity is! File || !entity.path.endsWith(".md")) continue;
    final name = basename(entity.path).replaceAll(".md", "");
    final content = entity.readAsStringSync();
    entries.add(BundledPromptFile(project, name, "", sha256Of(content),
        content));
  }
  return entries;
}