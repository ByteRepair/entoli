// Writes lib/data/builtin_models.dart: the models.dev entries of the presets'
// default models, so they can be picked before the first catalog fetch or
// without one. Fetches models.dev, so unlike the other generators it is run by
// hand when a preset's defaults change, and its output is committed.
//
// The defaults are read out of the source rather than imported: the domain
// imports Flutter, which `dart run` cannot load.
import "dart:convert";
import "dart:io";

import "gen_common.dart";

Future<void> main() async {
  final source = File("lib/domain/llm_provider.dart").readAsStringSync();
  final wanted = <String, Set<String>>{};
  // Each preset: its id, then the ids its default fields name.
  final presets = source.split("LlmProviderConfig(").skip(1);
  for (final preset in presets) {
    final id = RegExp(r'\bid: "([^"]+)"').firstMatch(preset)?.group(1);
    if (id == null) continue;
    for (final m in RegExp(r'default(?:Light)?ModelId: "([^"]+)"').allMatches(preset)) {
      wanted.putIfAbsent(id, () => {}).add(m.group(1)!);
    }
  }
  final images = RegExp(r'"([\w-]+)": "([^"]+)",').allMatches(
      source.substring(source.indexOf("imageDefaultOf")));
  for (final m in images.take(8)) {
    if (!wanted.containsKey(m.group(1))) continue;
    wanted[m.group(1)!]!.add(m.group(2)!);
  }

  final client = HttpClient();
  final request = await client.getUrl(Uri.parse("https://models.dev/api.json"));
  final body = await (await request.close()).transform(utf8.decoder).join();
  client.close();
  final all = jsonDecode(body) as Map<String, dynamic>;

  final kept = <String, dynamic>{};
  for (final MapEntry(key: provider, value: ids) in wanted.entries) {
    final entry = all[provider] as Map<String, dynamic>?;
    final models = entry?["models"] as Map<String, dynamic>? ?? const {};
    final found = {
      for (final id in ids)
        if (models[id] case final Map<String, dynamic> m) id: _parsed(m),
    };
    for (final id in ids.where((id) => !found.containsKey(id))) {
      stderr.writeln("models.dev lists no $provider/$id; left out.");
    }
    if (found.isEmpty) continue;
    kept[provider] = {"api": ?entry!["api"], "models": found};
  }

  final buf = StringBuffer()
    ..writeln("// GENERATED by tool/gen_builtin_models.dart — do not edit.")
    ..writeln("// models.dev's entries for the presets' default models, as of the")
    ..writeln("// last run; the fetched catalog replaces them.")
    ..writeln()
    ..writeln("const String builtinModelsJson = ${stringLiteral(jsonEncode(kept))};");
  writeGenerated("lib/data/builtin_models.dart", buf);
}

/// The fields `ModelInfo.fromJson` reads, and nothing it does not: the app
/// keeps only what it parses.
Map<String, dynamic> _parsed(Map<String, dynamic> m) {
  Map<String, dynamic>? pick(Object? from, List<String> keys) => from is Map
      ? {for (final k in keys) if (from[k] != null) k: from[k]}
      : null;
  return {
    "name": ?m["name"],
    "reasoning": ?m["reasoning"],
    "tool_call": ?m["tool_call"],
    "modalities": ?pick(m["modalities"], ["input", "output"]),
    "limit": ?pick(m["limit"], ["context", "output"]),
    "cost": ?pick(m["cost"], ["input", "output"]),
  };
}
